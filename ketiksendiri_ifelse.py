nama = 'lesley'
damage = 1200
hero_attacker = True

if hero_attacker == True and damage >= 1000:
    print (nama, ' itu hero attack mematikan')

elif hero_attacker == True and damage >= 500:
    print (nama, 'bisa attack, tapi kurang damage')

else :
    print (nama, 'itu bukan hero attacker bro')
